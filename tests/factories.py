"""테스트용 합성 원본 데이터(load_file 직후 형태) 빌더.

- 한솔: 실제 컬럼명을 가진 DataFrame (parse_hansol의 has_header 경로).
- 일마/차트: header=None 스타일 — 0행에 헤더 텍스트가 들어간 list-of-lists.
"""
import pandas as pd


def hansol_raw(**columns):
    """한솔페이 원본. 예: hansol_raw(금액=[...], 승인번호=[...], 거래시간=[...], ...)"""
    return pd.DataFrame(columns)


def table_raw(header, *rows):
    """header=None 스타일 표 (일마/차트 파서용). 0행=헤더 텍스트, 이후=데이터."""
    return pd.DataFrame([list(header), *[list(r) for r in rows]])


# ── 자주 쓰는 시나리오 프리셋 ────────────────────────────────

def basic_three_files():
    """승인번호로 깔끔히 연결되는 3파일 기본 시나리오.
    100 김철수 카드 50,000 / 200 이영희 카드 30,000 / 300 박민수 현금 20,000.
    """
    hansol = hansol_raw(
        금액=[50000, 30000, 20000],
        승인번호=["100111", "200222", "300333"],
        거래시간=["143025", "150010", "151500"],
        거래상태=["정상승인", "정상승인", "포인트사용승인"],
        구분=["카드", "카드", "현금"],
        매입사=["삼성카드", "현대카드", "현금영수증"],
        카드번호=["1234567890123456", "9876543210000000", ""],
    )
    daily = table_raw(
        ["내원순서", "차트번호", "성명", "카드", "현금", "이체"],
        [1, "100", "김철수", 50000, 0, 0],
        [2, "200", "이영희", 30000, 0, 0],
        [3, "300", "박민수", 0, 20000, 0],
    )
    patient = table_raw(
        ["차트번호", "이름", "결제수단", "비급여(과세총금액)", "본부금", "결제메모"],
        ["100", "김철수", "카드-삼성카드", 50000, 0, "100111"],
        ["200", "이영희", "카드-현대카드", 30000, 0, "200222"],
        ["300", "박민수", "현금영수증", 20000, 0, ""],
    )
    return hansol, daily, patient


def mismatch_three_files():
    """차트 200만 35,000(한솔·일마는 30,000) → ★★ 동일환자 확정(gap일치) 유발 시나리오."""
    hansol, daily, patient = basic_three_files()
    # 차트 200 금액을 35,000으로 변경
    patient.iloc[2, 3] = 35000  # (행=차트200, 열=비급여(과세총금액))
    return hansol, daily, patient
